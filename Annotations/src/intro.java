public class intro {
	public static void main(String[] args) {
		System.out.println("Annotations are most important in Java and start with @");
		System.out.println("They are used to attach metadata about classes, interfaces, and methods");
		System.out.println("Annotations can be used for various purposes such as compiler instructions, runtime processing, and documentation");
		System.out.println("Examples of annotations include:");
		System.out.println("@Override - informs the compiler that the method is intended to override a method in the superclass");
		System.out.println("@Deprecated - indicates that the method or class is no longer recommended for use");
		System.out.println("@SuppressWarnings - suppresses specific compiler warnings");
		System.out.println("@Target - specifies the types of elements to which the annotation can be applied");
		System.out.println("@Retention - specifies how long the annotation is retained");
		System.out.println("@Documented - indicates that the annotation should be documented by tools like JavaDoc");
		System.out.println("@Inherited - indicates that the annotation is inherited by subclasses");
		System.out.println("@FunctionalInterface - informs the compiler that the interface is intended to be a functional interface");
	}
}